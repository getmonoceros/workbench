import { promises as fsp } from 'node:fs';
import path from 'node:path';
import { consola } from 'consola';
import { matchMonocerosFeature } from '../util/ref.js';
import { workbenchRoot } from '../config/paths.js';
import { AGENTS, presentAgents, type Agent } from './agent-roles.js';
import type { CreateOptions } from './types.js';

/**
 * Materialize the `discovery-atlassian` feature: the seven skills that take
 * an idea to a brief, personas and journeys, a domain model, a design brief,
 * a technical brief and a Jira backlog, written for every coding agent the
 * workbench carries (ADR 0068).
 *
 * The skills used to ship as a Claude Code plugin from `monoceros-discovery`.
 * They live here now because they follow the CLI: the technical brief writes
 * `monoceros init` commands, so a skill and the CLI it describes change in
 * one commit. The mechanism is the one `agent-roles` uses (ADR 0067): one
 * text under `templates/discovery-atlassian/`, copied at apply, host-side,
 * into each agent's persistent skills directory (ADR 0018, ADR 0020).
 *
 *   - Claude Code: `~/.claude/skills/<skill>/`
 *   - OpenCode: `~/.config/opencode/skills/<skill>/`, plus a one-line command
 *     per skill, because OpenCode reaches a skill through its skill tool and
 *     not as `/name`
 *   - Copilot: `~/.copilot/skills/<skill>/`
 *
 * A skill reads only from its own directory, so the files several skills
 * share are kept once under `shared/` and copied into each skill that needs
 * them (`SHARED`).
 */

const FEATURE = 'discovery-atlassian';

/** The skills, by directory name. Also what is removed when they go. */
export const DISCOVERY_SKILLS = [
  'discovery-brief-atlassian',
  'discovery-personas-journeys-atlassian',
  'discovery-domain-model-atlassian',
  'discovery-design-atlassian',
  'discovery-tech-frame-atlassian',
  'planning-epics-stories-atlassian',
  'handoff-project-files-atlassian',
] as const;
type Skill = (typeof DISCOVERY_SKILLS)[number];

const DIAGRAM_SKILLS: readonly Skill[] = [
  'discovery-domain-model-atlassian',
  'discovery-tech-frame-atlassian',
];

/**
 * Which file under `shared/` goes into which skills, at the same relative
 * path. `diagram.mjs` finds its fonts at `../assets/fonts`, so they travel
 * with it.
 */
export const SHARED: Readonly<Record<string, readonly Skill[]>> = {
  'references/discovery-rules.md': DISCOVERY_SKILLS,
  'references/confluence-style.md': [
    'discovery-brief-atlassian',
    'discovery-personas-journeys-atlassian',
    'discovery-domain-model-atlassian',
    'discovery-design-atlassian',
    'discovery-tech-frame-atlassian',
  ],
  'scripts/diagram.mjs': DIAGRAM_SKILLS,
  'assets/fonts/Inter-Regular.ttf': DIAGRAM_SKILLS,
  'assets/fonts/Inter-SemiBold.ttf': DIAGRAM_SKILLS,
  'assets/fonts/OFL.txt': DIAGRAM_SKILLS,
};

/** The repository the plugin this feature replaces came from. */
const PLUGIN_REPO = 'github.com/getmonoceros/monoceros-discovery';

/** The docs MCP server's endpoint, however the builder named the entry. */
const DOCS_MCP_URL = 'mcp.getmonoceros.build';

const NOTICE =
  '<!-- Generated by `monoceros apply` from the discovery-atlassian feature. Edits here\n' +
  '     are overwritten on the next apply. -->\n';

interface SkillLayout {
  skillsDir: string;
  /** OpenCode only: where the slash command per skill goes. */
  commandsDir?: string;
}

function skillLayout(targetDir: string, agent: Agent): SkillLayout {
  const home = path.join(targetDir, 'home');
  switch (agent) {
    case 'claude-code':
      return { skillsDir: path.join(home, '.claude', 'skills') };
    case 'opencode': {
      const dir = path.join(home, '.config', 'opencode');
      return {
        skillsDir: path.join(dir, 'skills'),
        commandsDir: path.join(dir, 'commands'),
      };
    }
    case 'copilot':
      return { skillsDir: path.join(home, '.copilot', 'skills') };
  }
}

/**
 * Write the discovery skills for every coding agent present, or remove them
 * where the feature or the agent is gone: each skills directory is a
 * persistent bind mount, so what an earlier apply wrote stays live until
 * something deletes it. Says what the discovery still lacks, and carries on.
 */
export async function writeDiscovery(
  targetDir: string,
  containerName: string,
  opts: Pick<
    CreateOptions,
    'features' | 'mcpServers' | 'pluginMarketplaceUrls'
  >,
): Promise<void> {
  const enabled = hasFeature(opts.features, FEATURE);
  const agents = enabled ? presentAgents(opts.features) : [];
  const legacyPlugin = (opts.pluginMarketplaceUrls ?? []).some(
    (url) => normalizeUrl(url) === PLUGIN_REPO,
  );

  for (const agent of AGENTS) {
    if (!agents.includes(agent)) await removeSkills(targetDir, agent);
  }

  if (!enabled) {
    if (legacyPlugin) consola.warn(switchOverHint(containerName));
    return;
  }
  for (const hint of missingHints(containerName, opts, legacyPlugin)) {
    consola.warn(hint);
  }
  if (agents.length === 0) return;

  const templates = path.join(workbenchRoot(), 'templates', FEATURE);
  for (const agent of agents) {
    const layout = skillLayout(targetDir, agent);
    await fsp.mkdir(layout.skillsDir, { recursive: true });
    for (const skill of DISCOVERY_SKILLS) {
      await writeSkill(templates, path.join(layout.skillsDir, skill), skill);
    }
    if (layout.commandsDir) {
      await fsp.mkdir(layout.commandsDir, { recursive: true });
      for (const skill of DISCOVERY_SKILLS) {
        const front = await fsp.readFile(
          path.join(templates, 'skills', skill, 'SKILL.md'),
          'utf8',
        );
        await fsp.writeFile(
          path.join(layout.commandsDir, `${skill}.md`),
          opencodeCommand(skill, front),
        );
      }
    }
  }
}

/** One skill's directory: its own files, the shared ones, the notice. */
async function writeSkill(
  templates: string,
  dest: string,
  skill: Skill,
): Promise<void> {
  // Replaced whole, so a file the template dropped does not linger.
  await fsp.rm(dest, { recursive: true, force: true });
  await fsp.cp(path.join(templates, 'skills', skill), dest, {
    recursive: true,
  });
  for (const [file, skills] of Object.entries(SHARED)) {
    if (!skills.includes(skill)) continue;
    await fsp.mkdir(path.dirname(path.join(dest, file)), { recursive: true });
    await fsp.copyFile(
      path.join(templates, 'shared', file),
      path.join(dest, file),
    );
  }
  const skillFile = path.join(dest, 'SKILL.md');
  await fsp.writeFile(
    skillFile,
    withNotice(await fsp.readFile(skillFile, 'utf8')),
  );
}

/** The notice right after the frontmatter, where a reader of the file sees it. */
export function withNotice(body: string): string {
  const end = /^---\n[\s\S]*?\n---\n/.exec(body);
  if (!end) return NOTICE + '\n' + body;
  return end[0] + '\n' + NOTICE + body.slice(end[0].length);
}

/**
 * The OpenCode command that keeps `/<skill>` working the way it does in the
 * other agents. Its description is the first sentence of the skill's.
 */
export function opencodeCommand(skill: string, skillMd: string): string {
  const description =
    /^description:\s*(.+)$/m.exec(skillMd)?.[1]?.trim() ?? skill;
  const first = /^.*?\.(?=\s|$)/.exec(description)?.[0] ?? description;
  return (
    '---\n' +
    `description: ${JSON.stringify(first)}\n` +
    '---\n\n' +
    NOTICE +
    '\n' +
    `Load the \`${skill}\` skill with the skill tool and follow it.\n\n` +
    'What the user passed along with this command: $ARGUMENTS\n'
  );
}

async function removeSkills(targetDir: string, agent: Agent): Promise<void> {
  const layout = skillLayout(targetDir, agent);
  for (const skill of DISCOVERY_SKILLS) {
    await fsp.rm(path.join(layout.skillsDir, skill), {
      recursive: true,
      force: true,
    });
    if (layout.commandsDir) {
      await fsp.rm(path.join(layout.commandsDir, `${skill}.md`), {
        force: true,
      });
    }
  }
}

/**
 * What the discovery still lacks in this workbench, each with the command
 * that closes it. None of it stops the apply: the skills are written either
 * way, and the missing piece is one command away.
 */
export function missingHints(
  containerName: string,
  opts: Pick<CreateOptions, 'features' | 'mcpServers'>,
  legacyPlugin = false,
): string[] {
  const hints: string[] = [];
  if (presentAgents(opts.features).length === 0) {
    hints.push(
      `[${FEATURE}] this workbench has no coding agent yet, so the discovery skills have nothing to run in. Add one:\n` +
        `  monoceros add-feature ${containerName} claude\n` +
        `  monoceros add-feature ${containerName} opencode\n` +
        `  monoceros add-feature ${containerName} copilot`,
    );
  }
  const atlassian = featureOptions(opts.features, 'atlassian');
  if (!atlassian || String(atlassian.twg) === 'false') {
    hints.push(
      `[${FEATURE}] the discovery reads and writes Confluence and Jira through twg, which this workbench does not have. Add it with:\n` +
        `  monoceros add-feature ${containerName} atlassian/twg`,
    );
  }
  const docs = (opts.mcpServers ?? []).some(
    (s) => s.name === 'monoceros-docs' || (s.url ?? '').includes(DOCS_MCP_URL),
  );
  if (!docs) {
    hints.push(
      `[${FEATURE}] the technical brief reads the component catalog from the monoceros-docs MCP server, which this workbench does not register. Add it with:\n` +
        `  monoceros add-mcp-server ${containerName} monoceros-docs`,
    );
  }
  if (legacyPlugin) {
    hints.push(
      `[${FEATURE}] the claude-code entry still installs the discovery-atlassian plugin from monoceros-discovery, so Claude Code sees every discovery skill twice. ` +
        `Delete that entry under \`plugins:\` in container-configs/${containerName}.yml, then run:\n` +
        `  monoceros apply ${containerName}`,
    );
  }
  return hints;
}

/** For a workbench that still runs the discovery from the old plugin. */
export function switchOverHint(containerName: string): string {
  return (
    `[${FEATURE}] the discovery-atlassian plugin from monoceros-discovery is replaced by the discovery-atlassian feature, which serves every coding agent in the workbench. Switch over with:\n` +
    `  monoceros add-feature ${containerName} discovery-atlassian\n` +
    `then delete the plugin's entry under \`plugins:\` in container-configs/${containerName}.yml and run \`monoceros apply ${containerName}\`.`
  );
}

function normalizeUrl(url: string): string {
  return url
    .trim()
    .toLowerCase()
    .replace(/^https?:\/\//, '')
    .replace(/\/+$/, '')
    .replace(/\.git$/, '');
}

function hasFeature(features: CreateOptions['features'], name: string) {
  return featureOptions(features, name) !== undefined;
}

function featureOptions(
  features: CreateOptions['features'],
  name: string,
): Record<string, unknown> | undefined {
  if (!features) return undefined;
  const entry = Object.entries(features).find(
    ([ref]) => matchMonocerosFeature(ref)?.name === name,
  );
  return entry ? ((entry[1] ?? {}) as Record<string, unknown>) : undefined;
}
