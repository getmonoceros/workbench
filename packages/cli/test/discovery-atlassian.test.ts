import {
  mkdir,
  mkdtemp,
  readFile,
  readdir,
  rm,
  stat,
  writeFile,
} from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { consola } from 'consola';
import { parse as parseYaml } from 'yaml';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import {
  DISCOVERY_SKILLS,
  SHARED,
  missingHints,
  opencodeCommand,
  withNotice,
  writeDiscovery,
} from '../src/create/discovery-atlassian.js';
import { workbenchRoot } from '../src/config/paths.js';
import type { ResolvedMcpServer } from '../src/catalog/mcp.js';

const F = 'ghcr.io/getmonoceros/monoceros-features';
const DISCOVERY = `${F}/discovery-atlassian:1`;
const CLAUDE = `${F}/claude-code:1`;
const OPENCODE = `${F}/opencode:1`;
const COPILOT = `${F}/copilot:1`;
const ATLASSIAN = `${F}/atlassian:1`;
const NAME = 'acme';
const DOCS: ResolvedMcpServer = {
  name: 'monoceros-docs',
  transport: 'http',
  url: 'https://mcp.getmonoceros.build/mcp',
  fromCatalog: true,
};
const PLUGIN_URL = 'https://github.com/getmonoceros/monoceros-discovery.git';
const TEMPLATES = path.join(
  workbenchRoot(),
  'templates',
  'discovery-atlassian',
);

let dir: string;
let warn: ReturnType<typeof vi.spyOn>;

beforeEach(async () => {
  dir = await mkdtemp(path.join(tmpdir(), 'monoceros-discovery-'));
  warn = vi.spyOn(consola, 'warn').mockImplementation(() => {});
});

afterEach(async () => {
  warn.mockRestore();
  await rm(dir, { recursive: true, force: true });
});

const home = (...p: string[]) => path.join(dir, 'home', ...p);
const SKILL_DIRS = {
  get 'claude-code'() {
    return home('.claude', 'skills');
  },
  get opencode() {
    return home('.config', 'opencode', 'skills');
  },
  get copilot() {
    return home('.copilot', 'skills');
  },
};
const commandsDir = () => home('.config', 'opencode', 'commands');
const exists = (p: string) =>
  stat(p).then(
    () => true,
    () => false,
  );
const warnings = () => warn.mock.calls.map((c) => String(c[0]));

type Features = Record<string, Record<string, unknown>>;
const write = (
  features: Features,
  extra: { mcpServers?: ResolvedMcpServer[]; plugins?: string[] } = {},
) =>
  writeDiscovery(dir, NAME, {
    features: features as never,
    mcpServers: extra.mcpServers ?? [DOCS],
    pluginMarketplaceUrls: extra.plugins,
  });

const full = {
  [CLAUDE]: {},
  [OPENCODE]: {},
  [COPILOT]: {},
  [DISCOVERY]: {},
  [ATLASSIAN]: { twg: true },
};

describe('writeDiscovery', () => {
  it('writes every skill for every coding agent present', async () => {
    await write(full);
    for (const skillsDir of Object.values(SKILL_DIRS)) {
      for (const skill of DISCOVERY_SKILLS) {
        expect(await exists(path.join(skillsDir, skill, 'SKILL.md'))).toBe(
          true,
        );
      }
    }
  });

  it('writes only for the agents the workbench carries', async () => {
    await write({ [CLAUDE]: {}, [DISCOVERY]: {}, [ATLASSIAN]: {} });
    expect(await exists(SKILL_DIRS['claude-code'])).toBe(true);
    expect(await exists(SKILL_DIRS.opencode)).toBe(false);
    expect(await exists(SKILL_DIRS.copilot)).toBe(false);
  });

  it('copies each shared file into exactly the skills that need it', async () => {
    await write(full);
    for (const [file, skills] of Object.entries(SHARED)) {
      const source = await readFile(path.join(TEMPLATES, 'shared', file));
      for (const skill of DISCOVERY_SKILLS) {
        const at = path.join(SKILL_DIRS.copilot, skill, file);
        if (skills.includes(skill)) {
          expect(await readFile(at)).toEqual(source);
        } else {
          expect(await exists(at)).toBe(false);
        }
      }
    }
  });

  it('puts the diagram fonts where diagram.mjs looks for them', async () => {
    await write(full);
    const skill = path.join(
      SKILL_DIRS['claude-code'],
      'discovery-tech-frame-atlassian',
    );
    // diagram.mjs resolves its fonts at ../assets/fonts from its own folder.
    const script = await readFile(
      path.join(skill, 'scripts', 'diagram.mjs'),
      'utf8',
    );
    expect(script).toContain('join(HERE, "..", "assets", "fonts")');
    expect(
      await exists(path.join(skill, 'assets', 'fonts', 'Inter-Regular.ttf')),
    ).toBe(true);
  });

  it('marks every SKILL.md as generated, after its frontmatter', async () => {
    await write(full);
    const body = await readFile(
      path.join(SKILL_DIRS.opencode, 'discovery-brief-atlassian', 'SKILL.md'),
      'utf8',
    );
    expect(body.startsWith('---\nname: discovery-brief-atlassian\n')).toBe(
      true,
    );
    expect(body).toContain('Generated by `monoceros apply`');
    expect(body.indexOf('Generated by')).toBeGreaterThan(
      body.indexOf('\n---\n'),
    );
  });

  it('gives OpenCode a command per skill that loads it', async () => {
    await write(full);
    expect((await readdir(commandsDir())).sort()).toEqual(
      DISCOVERY_SKILLS.map((s) => `${s}.md`).sort(),
    );
    const command = await readFile(
      path.join(commandsDir(), 'discovery-brief-atlassian.md'),
      'utf8',
    );
    expect(command).toContain(
      'Load the `discovery-brief-atlassian` skill with the skill tool',
    );
    expect(command).toContain('$ARGUMENTS');
  });

  it('replaces a skill whole, so a file the template dropped goes', async () => {
    const stale = path.join(
      SKILL_DIRS['claude-code'],
      'discovery-brief-atlassian',
      'references',
      'old.md',
    );
    await mkdir(path.dirname(stale), { recursive: true });
    await writeFile(stale, 'old');
    await write(full);
    expect(await exists(stale)).toBe(false);
  });

  it('removes exactly the discovery skills when the feature goes', async () => {
    await write(full);
    const foreign = path.join(SKILL_DIRS['claude-code'], 'my-own-skill');
    await mkdir(foreign, { recursive: true });
    await writeFile(path.join(foreign, 'SKILL.md'), 'mine');
    await writeFile(path.join(commandsDir(), 'my-command.md'), 'mine');

    const { [DISCOVERY]: _gone, ...rest } = full;
    await write(rest);
    for (const skillsDir of Object.values(SKILL_DIRS)) {
      for (const skill of DISCOVERY_SKILLS) {
        expect(await exists(path.join(skillsDir, skill))).toBe(false);
      }
    }
    expect(await readdir(commandsDir())).toEqual(['my-command.md']);
    expect(await exists(path.join(foreign, 'SKILL.md'))).toBe(true);
  });

  it('removes the skills of an agent that left the workbench', async () => {
    await write(full);
    const { [COPILOT]: _gone, ...rest } = full;
    await write(rest);
    expect(await readdir(SKILL_DIRS.copilot)).toEqual([]);
    expect(
      await exists(path.join(SKILL_DIRS.opencode, DISCOVERY_SKILLS[0])),
    ).toBe(true);
  });

  it('says nothing for a complete workbench', async () => {
    await write(full);
    expect(warnings()).toEqual([]);
  });

  it('names the command for a missing twg, and still writes', async () => {
    await write({ [CLAUDE]: {}, [DISCOVERY]: {}, [ATLASSIAN]: { twg: false } });
    expect(warnings().join('\n')).toContain(
      'monoceros add-feature acme atlassian/twg',
    );
    expect(await exists(SKILL_DIRS['claude-code'])).toBe(true);
  });

  it('names the command for a missing monoceros-docs', async () => {
    await write(full, { mcpServers: [] });
    expect(warnings().join('\n')).toContain(
      'monoceros add-mcp-server acme monoceros-docs',
    );
  });

  it('takes the docs server under another name by its URL', () => {
    const hints = missingHints(NAME, {
      features: full as never,
      mcpServers: [{ ...DOCS, name: 'docs' }],
    });
    expect(hints).toEqual([]);
  });

  it('names the agents to add when there is none', async () => {
    await write({ [DISCOVERY]: {}, [ATLASSIAN]: {} });
    expect(warnings().join('\n')).toContain(
      'monoceros add-feature acme claude',
    );
  });

  it('asks to switch over from the old plugin', async () => {
    const { [DISCOVERY]: _gone, ...rest } = full;
    await write(rest, { plugins: [PLUGIN_URL] });
    expect(warnings().join('\n')).toContain(
      'monoceros add-feature acme discovery-atlassian',
    );
  });

  it('asks to drop the old plugin next to the feature', async () => {
    await write(full, {
      plugins: ['https://github.com/getmonoceros/monoceros-discovery'],
    });
    expect(warnings().join('\n')).toContain('sees every discovery skill twice');
  });
});

describe('the shipped skills', () => {
  it('has a template directory for every skill and a source for every shared file', async () => {
    expect((await readdir(path.join(TEMPLATES, 'skills'))).sort()).toEqual(
      [...DISCOVERY_SKILLS].sort(),
    );
    for (const file of Object.keys(SHARED)) {
      expect(await exists(path.join(TEMPLATES, 'shared', file))).toBe(true);
    }
  });

  it('has frontmatter every agent can parse as YAML', async () => {
    // Copilot CLI parses the frontmatter strictly and skips a skill whose
    // description holds an unquoted ': ' (a real run lost
    // planning-epics-stories-atlassian this way); Claude Code had read it.
    for (const skill of DISCOVERY_SKILLS) {
      const body = await readFile(
        path.join(TEMPLATES, 'skills', skill, 'SKILL.md'),
        'utf8',
      );
      const front = /^---\n([\s\S]*?)\n---\n/.exec(body)?.[1] ?? '';
      const parsed = parseYaml(front) as Record<string, unknown>;
      expect(parsed.name).toBe(skill);
      expect(typeof parsed.description).toBe('string');
    }
  });

  it('names no agent-specific question tool', async () => {
    // The skills run in Claude Code, OpenCode and Copilot alike: they ask,
    // and each agent uses its own way of asking (ADR 0068).
    for (const skill of DISCOVERY_SKILLS) {
      const body = await readFile(
        path.join(TEMPLATES, 'skills', skill, 'SKILL.md'),
        'utf8',
      );
      expect(body).not.toContain('AskUserQuestion');
    }
    const rules = await readFile(
      path.join(TEMPLATES, 'shared', 'references', 'discovery-rules.md'),
      'utf8',
    );
    expect(rules).not.toContain('AskUserQuestion');
  });

  it('keeps a proposal inside the question that asks about it', async () => {
    // A real run in Copilot: the brief's proposal stood as text before the
    // question dialog, the dialog covered it, and the user was asked to
    // confirm a sentence they could not see.
    const rules = await readFile(
      path.join(TEMPLATES, 'shared', 'references', 'discovery-rules.md'),
      'utf8',
    );
    expect(rules).toContain('## A proposal stands in the question');
    for (const skill of DISCOVERY_SKILLS) {
      const body = await readFile(
        path.join(TEMPLATES, 'skills', skill, 'SKILL.md'),
        'utf8',
      );
      expect(body).toContain('Read `references/discovery-rules.md`');
    }
  });

  it('asks which coding agents the build workbench gets', async () => {
    // A real run in OpenCode: the technical brief settled on `claude` as a
    // fixed default, the page and the handoff followed, and the user worked
    // with OpenCode the whole time.
    const dir = path.join(
      TEMPLATES,
      'skills',
      'discovery-tech-frame-atlassian',
    );
    const skill = await readFile(path.join(dir, 'SKILL.md'), 'utf8');
    expect(skill).toContain('**The coding agents, and this one you ask**');
    expect(skill).toContain('exactly two of them are questions');
    expect(skill).toContain(
      'The agent this\n     session runs in is the first option and marked as the recommendation',
    );
    expect(skill).toContain('monoceros remove-feature <name> claude');
    const page = await readFile(
      path.join(dir, 'references', 'templates.md'),
      'utf8',
    );
    expect(page).toContain('one line per chosen coding agent');
    expect(page).toContain('monoceros remove-feature {name} claude');
  });

  it('reads a write from its output file instead of repeating it', async () => {
    // A real run in OpenCode: twg handed the create's result over as a file,
    // the agent could not parse the output, ran the create again, and the
    // backlog got a duplicate epic.
    const rules = await readFile(
      path.join(TEMPLATES, 'shared', 'references', 'discovery-rules.md'),
      'utf8',
    );
    expect(rules).toContain('## A write is never repeated to see its result');
    expect(rules).toContain('output_files:');
  });

  it('no longer points at the plugin or the retired role features', async () => {
    for (const skill of DISCOVERY_SKILLS) {
      const dirFiles = await readdir(path.join(TEMPLATES, 'skills', skill), {
        recursive: true,
      });
      for (const file of dirFiles) {
        if (!String(file).endsWith('.md')) continue;
        const body = await readFile(
          path.join(TEMPLATES, 'skills', skill, String(file)),
          'utf8',
        );
        expect(body).not.toMatch(/claude-code-roles|opencode-roles/);
        expect(body).not.toContain('monoceros-discovery.git');
      }
    }
  });
});

describe('helpers', () => {
  it('withNotice puts the notice after the frontmatter', () => {
    expect(withNotice('---\nname: x\n---\n\n# X\n')).toMatch(
      /^---\nname: x\n---\n\n<!-- Generated[\s\S]*-->\n\n# X\n$/,
    );
  });

  it('opencodeCommand takes the first sentence of the description', () => {
    const md =
      '---\nname: s\ndescription: Does one thing. Use it when asked.\n---\n';
    expect(opencodeCommand('s', md)).toContain(
      'description: "Does one thing."',
    );
  });
});
