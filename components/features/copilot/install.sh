#!/usr/bin/env bash
# Monoceros devcontainer feature: copilot.
#
# Installs GitHub Copilot CLI from GitHub's official install script: one
# standalone binary, no Node runtime needed. The permission mode and the
# trusted workspace folder are NOT handled here; `monoceros apply` writes them
# into ~/.copilot (see create/copilot-settings.ts), so a yml change takes
# effect on the next apply instead of being frozen in the feature's cached
# image layer (ADR 0018). Auth and session state live under ~/.copilot, which
# is bind-mounted from the host so it survives apply rebuilds.

set -euo pipefail

# The binary goes into a directory the runtime user owns. Copilot updates
# itself into its package cache (~/.cache/copilot/pkg) and then also tries to
# replace its own executable; in a root-owned /usr/local/bin that second step
# fails with EACCES on every update. The update still works, the error is just
# noise, and noise in an update message reads like a broken install.
PREFIX=/opt/copilot

echo "[copilot] installing GitHub Copilot CLI into ${PREFIX}"
install -d -o node -g node "${PREFIX}"
TMP="$(mktemp)"
curl -fsSL -o "${TMP}" https://gh.io/copilot-install
# mktemp creates the file 0600 for root; the installer runs as node.
chmod 0644 "${TMP}"
runuser -u node -- env PREFIX="${PREFIX}" bash "${TMP}"
rm -f "${TMP}"

# `copilot` on PATH is a thin wrapper, not a symlink. Copilot reads and writes
# without asking only below the directory it starts in. Started in
# projects/<app>, it would ask before every read of the workspace briefing
# (AGENTS.md, .monoceros/) and could not register the project in the
# .code-workspace file, as the briefing tells it to. --add-dir grants the
# workspace root for the session. Nothing else changes: the environment, the
# token included, reaches Copilot as it is.
cat >/usr/local/bin/copilot <<'WRAPPER'
#!/bin/sh
# Auto-generated by the Monoceros copilot feature. See its install.sh.
if [ -n "${MONOCEROS_WORKSPACE_FOLDER:-}" ] && [ -d "${MONOCEROS_WORKSPACE_FOLDER}" ]; then
  exec /opt/copilot/bin/copilot --add-dir "${MONOCEROS_WORKSPACE_FOLDER}" "$@"
fi
exec /opt/copilot/bin/copilot "$@"
WRAPPER
chmod 0755 /usr/local/bin/copilot

runuser -u node -- bash -lc 'copilot --version' >/dev/null 2>&1 || {
  echo "[copilot] ERROR: install completed but \`copilot\` is not on PATH" >&2
  exit 1
}

# ─── Refresh hook (ADR 0054) ──────────────────────────────────────
# Copilot keeps itself current through its own updater, which downloads into
# the persisted package cache and applies the new version at the next launch.
# This hook makes that happen during apply instead of during the builder's
# first session after it: `copilot update` is one release lookup when nothing
# is new.
REFRESH_DIR=/usr/local/share/monoceros/refresh.d
mkdir -p "${REFRESH_DIR}"
cat >"${REFRESH_DIR}/copilot.sh" <<'HOOK'
#!/usr/bin/env bash
# Auto-generated by the Monoceros copilot feature.
#
# Keeps `copilot` current across applies (ADR 0054). Deliberately no `set -e`
# and no `pipefail`: best-effort by contract. No network or a GitHub hiccup
# must never fail an apply; the version already there still works.
set -u

note() {
  [ -n "${MONOCEROS_REFRESH_LOG:-}" ] || return 0
  printf '%s\n' "$1" >>"${MONOCEROS_REFRESH_LOG}" 2>/dev/null || true
}

version_of() {
  copilot --version 2>/dev/null | grep -oE '[0-9]+\.[0-9]+\.[0-9]+' | head -n1
}

installed="$(version_of)"
if ! copilot update >/dev/null 2>&1; then
  note "copilot: could not check for updates, keeping ${installed:-the installed version}"
  exit 0
fi
after="$(version_of)"
if [ "${after}" = "${installed}" ]; then
  note "copilot ${after:-unknown} (already current)"
else
  note "copilot ${after:-unknown} (updated from ${installed:-unknown})"
fi
HOOK
chmod 0755 "${REFRESH_DIR}/copilot.sh"

echo "[copilot] done. Without an apiToken in the yml, run \`/login\` once inside Copilot."
